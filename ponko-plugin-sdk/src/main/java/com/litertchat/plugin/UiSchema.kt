package com.litertchat.plugin

import android.os.Parcelable
import kotlinx.parcelize.Parcelize

/**
 * 插件设置页的**整页数据**。宿主拿它渲染出界面，插件自己不画 UI。
 *
 * ## 为什么是「宿主渲染」
 *
 * 插件**读不到宿主的 `PonkoTheme`**（它在 `app` module，不在 SDK 里）。插件要自己画，
 * 就得重写一套配色，而且 Ponko 的浅色/深色两套都得各写一遍，主题切换还跟不上。
 * 所以插件只提供一份「字段清单」，样式由宿主决定。
 *
 * ## 值归插件管
 *
 * 宿主**不持久化**任何设置值。每次要看设置就调 `getSettingsSchema()` 拿最新状态。
 * 插件最清楚自己的默认值、模型是否就绪、哪些项互斥 —— 宿主存一份必然出现
 * 「宿主以为是这样、插件实际是那样」，这类 bug 极难查。
 *
 * @param intro 整页顶部的说明段落，可为空
 * @param items 按顺序渲染的设置项；**空列表是合法的**（表示"这个插件没有可配置项"），
 *              宿主应显示成空页面而不是报错
 */
@Parcelize
data class UiSchema(
    val intro: String = "",
    val items: List<UiItem> = emptyList(),
) : Parcelable {

    /** 没有可渲染的项 —— 宿主据此显示"该插件没有界面" */
    val isEmpty: Boolean get() = intro.isBlank() && items.isEmpty()
}

/**
 * 一个设置项。宿主按 [type] 决定用什么控件画。
 *
 * @param key 稳定键。插件用它存值；宿主只原样带回，**不解释内容**
 * @param type 见 [UiType]
 * @param label 主文字：开关/滑块的标题、「按钮的文案」、`INFO` 的正文
 * @param help 次要说明，显示在控件下方，可为空
 * @param value 当前值（**字符串化**）：开关 `"true"`/`"false"`，滑块 `"2.0"`，
 *              单选是选中的 `UiOption.value`，输入框是原文
 * @param min 仅 [UiType.SLIDER]
 * @param max 仅 [UiType.SLIDER]
 * @param step 仅 [UiType.SLIDER]
 * @param options 仅 [UiType.CHOICE]
 * @param enabled `false` = 灰显且不可点。**不要隐藏** —— 用户要能看到「为什么这个不能点」
 * @param primary `true` = 视觉强调（如「下载模型」这种关键动作）
 */
@Parcelize
data class UiItem(
    val key: String = "",
    val type: Int,
    val label: String = "",
    val help: String = "",
    val value: String = "",
    val min: Double = 0.0,
    val max: Double = 1.0,
    val step: Double = 0.1,
    val options: List<UiOption> = emptyList(),
    val enabled: Boolean = true,
    val primary: Boolean = false,
) : Parcelable

/** [UiType.CHOICE] 的一个选项 */
@Parcelize
data class UiOption(
    val value: String,
    val label: String,
) : Parcelable

/**
 * 控件类型。
 *
 * ## 加一种类型 = 主 app 必须更新
 *
 * 这一点必须提前讲清楚：**控件是宿主画的，所以宿主不认识一个新类型，就画不出来。**
 * 插件单方面用了新类型，老宿主只能降级成纯文本（不会崩，但那个控件没了）。
 *
 * 所以这个集合要**一次放够**。判断标准是：
 * 「一个配置型插件，在不能写代码的前提下，最可能需要哪些控件？」
 *
 * ## 为什么是这 12 种
 *
 * 前 7 种覆盖「配置项」本身（说明、分组、布尔、数值、单选、输入、按钮）。
 * 后 5 种（[PROGRESS] / [STATUS] / [TEXTAREA] / [GROUP_START] / [GROUP_END]）
 * 是 2026-10-21 补的，全部来自「做 VoxCPM2 时一定会撞上」的四个具体场景：
 *
 * | 场景 | 缺了会怎样 |
 * |---|---|
 * | 下载 2.8GB 模型要看进度 | 没有 [PROGRESS]，用户盯着不动的界面以为卡死 |
 * | 「模型：已加载 2.8GB」这种只读信息 | 用 [INFO] 也能写，但和正文混在一起看不出来 |
 * | 音色描述要写一段话 | [TEXT] 是单行，长文本根本没法输入 |
 * | 参数十来个、一屏铺满 | 没有折叠，用户要滚很久才能看到下面 |
 *
 * ## v4 又加了 3 种（2026-10-22）
 *
 * | 场景 | 缺了会怎样 |
 * |---|---|
 * | 模型加载/推理过程想给用户看 | 没有 [LOG]，只能塞 `debugInfo`，用户要开 adb 才看得到 |
 * | 图像生成、修图要显示结果 | 没有 [IMAGE]，插件根本送不出图 |
 * | 合成完想试听、想拖到某一句 | 没有 [AUDIO]，只有宿主自己的「播放」按钮，不能 seek |
 *
 * 这三种和前 12 种有一个本质区别：**它们不是"配置项"，是"过程和产物"**。
 * 所以它们不参与 `setSetting`（用户不能改它们的值），
 * 内容靠 [IPonkoCallback.onUiPatch] / [IPonkoCallback.onImage] 单独送。
 *
 * ## 仍然刻意不做的
 *
 * 嵌套布局（一行放两个控件）、表格、自定义绘制（波形预览）、
 * **多图网格**（一次显示结果 A/B 两组对比）。
 * 这些要么让渲染代码爆炸，要么必须由插件自己画。
 * 多图确实有需求，但正确的形态是先想清楚"对比"这个交互（哪张是原图、
 * 点一下能不能互换），而不是先开放一个 `n 列` 的格子。
 *
 * ## 插件能不能自己布控件位置
 *
 * **现在不能。** 插件只决定「有哪些项、什么顺序」（`items` 是一个有序列表），
 * 每一项**纵向排列**，位置由宿主决定。
 *
 * 这是刻意的取舍，不是没做完：
 * · 布局代码一旦放开，插件就得自己处理深浅色、字号缩放、横竖屏、RTL ——
 *   而它读不到 `PonkoTheme`，两套主题各写一遍，主题切换还跟不上
 * · 有序列表已经能表达"哪个在上、哪个在一起"，缺的只是**并列**和**分栏**
 *
 * 如果确实需要并排（比如「语速」和「音高」两个滑块放一行），
 * 正确的做法是**在宿主侧加一种布局容器**（`ROW_START` / `ROW_END`，类似
 * 已有的 `GROUP_START` / `GROUP_END`），而不是把布局能力交给插件。
 * 代价是宿主多一份渲染代码，好处是所有插件自动拿到同一套主题适配。
 *
 * > 注：之前这里写过"走 `advancedActivity` 逃生口"，**那个东西从来没有实现过** ——
 * > 字段和宿主代码都不存在，只是文档里的一句臆想。已删掉，别照着它设计。
 */
object UiType {
    /** 纯文本段落（[UiItem.label] 即正文） */
    const val INFO = 0
    /** 分组标题 */
    const val SECTION = 1
    /** 开关。value 是 "true"/"false" */
    const val SWITCH = 2
    /** 滑块。用 min/max/step，value 是数字字符串 */
    const val SLIDER = 3
    /** 单选。使用 options + value */
    const val CHOICE = 4
    /** 单行文本输入 */
    const val TEXT = 5
    /**
     * 按钮。点了走 `invokeAction(key)`。
     *
     * 注意：按钮**没有值**，插件在 `invokeAction` 里做完事后调
     * `onSchemaChanged()` 让宿主重画（比如"下载模型"完成后把按钮变成"已下载"）。
     *
     * ## v9：`value` 可以点名**宿主动作**
     *
     * 把 `value` 写成 [HostActionId] 里的常量，这个按钮就改由**宿主执行**，
     * 不再是"回调插件"：
     *
     * ```kotlin
     * // 插件自己的按钮（value 空）
     * UiItem(key = "dl", type = UiType.ACTION, label = "下载模型")
     *
     * // 宿主的合成动作，但文案、位置、所在标签页都由插件决定
     * UiItem(key = "go", type = UiType.ACTION, label = "开始推理",
     *        value = HostActionId.REASONING, primary = true)
     * ```
     *
     * 被点名的动作会**从宿主顶部那排移走**，只出现在你放的位置 ——
     * 逐个覆盖：你只接管「合成」，其余四个仍在顶部。
     *
     * 为什么执行不能交给插件：这些动作背后是宿主的状态机（引擎加载了几成、
     * 是否正在合成、参考音频 FD、播放器、系统音乐库）。插件在另一个进程里
     * 这些都拿不到。能放开的只有**放哪些、放哪里、叫什么**。
     *
     * ### 三个约束
     *
     * | 项 | 谁说了算 |
     * |---|---|
     * | `label`（按钮叫什么） | **插件**。写了就用你的；不写用宿主默认 |
     * | `primary`（实心还是浅底） | **插件** |
     * | `enabled`（能不能点） | **宿主**。`UiItem.enabled` 对这个按钮**无效** |
     *
     * 最后一条是刻意的：插件不知道引擎加载到几成、是不是正在合成。
     * 让它说了算会出现"插件说能点、宿主拒绝"的死路。
     *
     * 另外 `engine` 的文案会被宿主按状态改写（加载 ↔ 卸载），你写的会被覆盖 ——
     * 那是状态语义，不是排版。
     */
    const val ACTION = 6

    // ==================== v2 补充 ====================

    /**
     * 只读进度条。
     *
     * [UiItem.value] 是**百分比 0–100 的字符串**（如 `"37.5"`）。
     * 不要用 min/max 表达真实数值范围 —— 那些留给 [SLIDER]，
     * 真实范围写在 [UiItem.help] 里（如 `"1.05 / 2.83 GB"`）。
     *
     * 用途：模型下载、长任务进度。**这个控件是只读的**，用户点不动它。
     */
    const val PROGRESS = 7

    /**
     * 只读状态行：左边 [UiItem.label]，右边 [UiItem.value]，灰底。
     *
     * 用于「模型：已加载」「设备：8 核 / 可用 3.2GB」这类**只需要看**的信息。
     * 和 [INFO] 的区别：状态行是「键 → 值」的对齐结构，一眼能扫；
     * [INFO] 是一段话，适合解释。
     */
    const val STATUS = 8

    /**
     * 多行文本输入。用法同 [TEXT]，但可以换行。
     *
     * 用于音色描述、提示词、歌词这类长文本。宿主显示成 3–4 行高、
     * 高度随内容增长的输入框。
     */
    const val TEXTAREA = 9

    /**
     * 可折叠分组的**开始**。[UiItem.label] 是分组标题，
     * [UiItem.key] 用来记住折叠状态（重启 App 后不忘）。
     *
     * 和 [GROUP_END] 成对使用，**不支持嵌套**（嵌套会让渲染和缩进都变复杂，
     * 而实际配置页很少需要超过一层）。
     *
     * 分组默认**展开** —— 用户点进来是要看内容的，默认收起等于藏起来。
     */
    const val GROUP_START = 10

    /** 可折叠分组的**结束**。没有其他字段。 */
    const val GROUP_END = 11

    // ==================== v4 补充：看得见的过程与产物 ====================

    /**
     * **只读日志框**（v4）。固定高度、自己内部滚动、可长按复制。
     *
     * 用途：模型加载日志、推理过程、原生库的 stderr —— 那些"用户不一定要看，
     * 但出了问题必须能拿出来"的内容。
     *
     * ## 字段用法
     *
     * | 字段 | 含义 |
     * |---|---|
     * | [UiItem.label] | 标题，空 = 不画标题行 |
     * | [UiItem.value] | 初始内容（可多行）。**只用于首次/整页刷新** |
     * | [UiItem.help] | 底部说明，空 = 不显示 |
     *
     * ## 怎么追加（不要靠刷新 schema）
     *
     * 用 [IPonkoCallback.onUiPatch]，`append = true`：
     * 宿主只往那一个 TextView 末尾加字，**不重建整页** ——
     * 滚动位置、输入框焦点、正在编辑的 [TEXTAREA] 都不会被打断。
     *
     * 走 `onSchemaChanged()` 全量重画的话，每来一行日志整页都要重建一次：
     * 用户滚到一半被拉回顶部，输入框失焦，很卡。
     *
     * ⚠ 宿主内部按 [`UiItem.key`] 找控件，所以**同一页里的 key 必须唯一**。
     * key 空的话也能显示，但无法被 [IPonkoCallback.onUiPatch] 更新。
     */
    const val LOG = 12

    /**
     * **结果图**（v4）。等宽、等比、可点击放大。
     *
     * 图片来源是 [IPonkoCallback.onImage]，**不是** [UiItem.value] ——
     * 图片走文件描述符，不挤 Binder 那 1MB 配额（和音频同样的理由）。
     *
     * ## 字段用法
     *
     * | 字段 | 含义 |
     * |---|---|
     * | [UiItem.label] | 标题，空 = 不画 |
     * | [UiItem.value] | **还没图时**显示的占位文字，如「点上面的按钮生成图片」 |
     * | [UiItem.help] | 底部说明 |
     *
     * 收到图之前显示占位文字，收到后替换成图片。再收到一张就换掉旧的
     * （只保留最新一张 —— 多图排列是另一种控件，见 [UiType] 的说明）。
     */
    const val IMAGE = 13

    /**
     * **音频播放条**（v4）：播放/暂停 + 可拖动进度 + 「0:03 / 0:12」。
     *
     * ## 播的是哪段音频
     *
     * 按 [UiItem.key] 找：
     *
     * 1. **插件送过文件**（v7，`notifyAudioFile(key, …)`）→ 播插件那份，各自独立
     * 2. 没送过 → 退回**宿主持有的那份产物**（最近一次由宿主发起的合成结果）
     *
     * 所以 v4 的老插件（只放一个播放器、不送文件）行为完全不变；
     * 想做"历史记录每条单独播"的，就给每条 `key` 各送一份文件。
     *
     * · 还没有任何产物时 → 显示"还没有可播放的音频"，按钮灰掉
     * · 产物换了一份 → 进度条自动归零
     *
     * ## 为什么不做成插件自己播
     *
     * 插件在**另一个进程**里。它自己播的话，退出这个页面声音还在响，
     * 用户找不到地方停 —— 宿主看不见也管不了别人的 MediaPlayer。
     * 而且"播放"这件事宿主已经有实现（音频焦点、来电打断），不该有第二份。
     *
     * ## 字段用法
     *
     * | 字段 | 含义 |
     * |---|---|
     * | [UiItem.key] | 音频归属。送过同名文件就播它，否则播宿主最近产物 |
     * | [UiItem.label] | 标题，空 = 不画 |
     * | [UiItem.help] | 说明，空 = 不显示 |
     */
    const val AUDIO = 14

    // ==================== v5 补充：页中页 ====================

    /**
     * 一组标签页的**开始**（v5）。
     *
     * 写成三段式 `TABS_START` / [TAB] / [TABS_END]，和 [GROUP_START] / [GROUP_END]
     * 同一套思路，这样**天然支持嵌套** —— 页中页中页只是再套一层。
     *
     * ## 字段用法
     *
     * | 字段 | 含义 |
     * |---|---|
     * | [UiItem.label] | 整组的标题，空 = 不画（内层通常留空，省一层视觉噪音） |
     * | [UiItem.key] | 记住"上次停在哪个页"。**强烈建议写**，否则改名/增删 tab 后选中项会错位 |
     *
     * ## 切换是纯 visibility，不重新渲染
     *
     * 宿主一次把所有页都建好，切换只改可见性。所以：
     * · 切回来时输入框内容、滚动位置都还在
     * · **插件自己的状态要留在自己那边** —— 切 tab 不会通知你
     *   （`setSetting` 只在用户改值时来，不在切页时来）
     *
     * ## ⚠ 别把标签页当"分组"用
     *
     * 两三个 tab 是有意义的（「参数 / 结果」）。**五个以上在手机上已经难用了** ——
     * 标签条会被挤成一排看不全的小字。参数多的话用 [GROUP_START] 折叠，
     * 那才是它该干的活。
     */
    const val TABS_START = 15

    /**
     * 一个标签页（v5）。必须写在 [TABS_START] 与 [TABS_END] 之间。
     *
     * [UiItem.label] 是**标签文字**（如「文生图」），[UiItem.key] 是该页的稳定标识。
     * 从这个 item 之后、到下一个 [TAB] 或 [TABS_END] 之前的所有项，都属于这一页。
     *
     * 标签文字**尽量短**：一行放 3~4 个是上限，超出会被省略号截断。
     */
    const val TAB = 16

    /** 一组标签页的**结束**（v5）。没有其他字段。 */
    const val TABS_END = 17

    // ==================== v6 补充：模型文件槽位 ====================

    /**
     * 一个**模型文件槽位**（v6）：宿主画成「槽位名 · 当前状态 · [导入] [清除]」一行。
     *
     * ## 为什么插件不能自己弹文件选择器
     *
     * 插件是 bound **Service**，在另一个进程里：
     * · `startActivityForResult` 是 Activity 的 API，Service 没有
     * · Android 10+ 禁止后台启动 Activity —— 用户点“导入”那一刻插件不在前台，
     *   真发起了也会被系统拦掉
     *
     * 所以**选择器必须由宿主弹**。插件能做的只是"声明我要这几份文件"，
     * 宿主替它弹选择器、拿到 FD、再把 FD 转给插件。
     *
     * ## 字段用法
     *
     * | 字段 | 含义 |
     * |---|---|
     * | [UiItem.key] | **模型角色**（如 `"base_lm"`），必须非空且在本插件内唯一。导入/删除都靠它定位 |
     * | [UiItem.label] | 槽位名（如「主干模型 BaseLM」） |
     * | [UiItem.value] | **当前状态**，插件自己报告：已导入就写大小（如 `"2.83 GB"`），没有就留空或写「未导入」 |
     * | [UiItem.help] | 底部说明，如 `"需要 VoxCPM2 的 .safetensors 主干"` |
     * | [UiItem.enabled] | `false` = 两按钮都灰掉（比如引擎正在运行、不能换模型） |
     *
     * ## 导入之后
     *
     * 宿主调 [IPonkoPlugin.importModel]，插件的活是：
     * 1. 在**工作线程**把这个 FD 读完、写进自己的私有目录（`filesDir` 之类）
     * 2. 读完 close 掉那个 FD（它是 dup 过的，关它不影响宿主）
     * 3. 调 `notifySchemaChanged()` 让宿主重画 —— 新状态就在上表 `value` 里
     *
     * **磁盘上只有一份**：宿主只是把 SAF 的 FD 转发过来，它自己不落盘。
     * 这和「宿主模型页导入」的最终代价一样（都是复制一次到自己的私有目录）。
     */
    const val MODEL_SLOT = 18

    // ==================== v7 补充：宿主功能块插槽 ====================

    /**
     * **宿主功能块的坑位**（v7）。
     *
     * 插件在自己的 schema 里放一个这种 item，宿主就把自己那块「功能」
     * （加载引擎 / 合成 / 播放 / 停止 / 保存 + 试听参数）画在**这个位置**，
     * 而不是永远钉在标题下面。
     *
     * ```kotlin
     * TABS_START(key = "main")
     *   TAB(key = "param", label = "参数")
     *     UiItem(type = UiType.HOST_SLOT)          // ← 宿主把功能块塞这儿
     *     UiItem(key = "cfg", type = UiType.SLIDER, …)
     *   TAB(key = "result", label = "结果")
     *     UiItem(key = "play", type = UiType.AUDIO, …)
     * TABS_END
     * ```
     *
     * ## 规则
     *
     * · **只认第一个**。放多个也只有第一个生效，其余的什么都不画（不是画两遍）
     * · **不写就不变**：老插件没这个 item → 功能块仍在标题下面，完全向后兼容
     * · 放进 tab 里意味着**只有切到那一页才看得到**这些按钮 —— 这是你要的取舍，
     *   宿主不会替你复制一份到别处
     * · 字段全部不用（`key`/`label`/`value` 都忽略）。写 `key` 只为你自己好读
     *
     * ## 为什么不是"整个功能块由插件重画"
     *
     * 那套按钮背后是宿主的状态机（引擎是否已加载、是否正在合成、
     * 参考音频 FD、保存到音乐库）。插件重画就得把这些状态也搬过去，
     * 两边各存一份必然打架。这里只是**改挂载点**，逻辑仍然只有一份。
     */
    const val HOST_SLOT = 19

    /**
     * 宿主认识的**最大**类型编号。
     *
     * 给宿主做兜底用：`type > MAX_KNOWN` 说明插件用了更新的控件。
     * 也给插件作者参考 —— 你用的类型超过这个值，就得要求用户更新 Ponko。
     */
    const val MAX_KNOWN = 19
}
